// A faster drop-in for makefun-site 1.0.0: run(input) returns exactly the output tree its build returns, produced by a
// single-purpose implementation of the same rules (front matter, slug, Markdown subset, template dialect, pipeline).
// Written for speed: hand-scanned parsers instead of regex-per-line, index-range inline rendering instead of slice
// recursion, and run-based HTML escaping instead of a regex replace per character.

// ---------------------------------------------------------------- text rules

const ESCAPES = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' };

/** `text` with & < > " and ' escaped; returns the input itself when nothing needs escaping. */
const ESCAPE_ANY = /[&<>"']/;
const ESCAPE_ALL = /[&<>"']/g;
function escapeHtml(text) {
  if (!ESCAPE_ANY.test(text)) return text;
  return text.replace(ESCAPE_ALL, (c) => ESCAPES[c]);
}

const SLUG_MAX = 64;

/**
 * The slug of `text`: NFKD, combining marks dropped, A-Z lowered, every run of characters other than a-z and 0-9 one
 * "-", none at either end, at most SLUG_MAX characters (a "-" left at the cut dropped), "untitled" when empty.
 */
function slugify(text) {
  let plain = text;
  let ascii = true;
  for (let i = 0; i < text.length; i++) if (text.charCodeAt(i) > 127) { ascii = false; break; }
  if (!ascii) plain = text.normalize('NFKD').replace(/\p{M}/gu, '');
  let out = '';
  let gap = false;
  for (let i = 0; i < plain.length; i++) {
    const ch = plain[i];
    let keep = null;
    if (ch >= 'A' && ch <= 'Z') keep = ch.toLowerCase();
    else if ((ch >= 'a' && ch <= 'z') || (ch >= '0' && ch <= '9')) keep = ch;
    if (keep === null) {
      gap = out.length > 0;
      continue;
    }
    if (gap) out += '-';
    gap = false;
    out += keep;
  }
  out = out.slice(0, SLUG_MAX).replace(/-+$/, '');
  return out === '' ? 'untitled' : out;
}

/** `slug` made unique against `taken` (and added to it): the first of slug, slug-2, slug-3 ... not taken. */
function uniqueSlug(slug, taken) {
  let out = slug;
  for (let n = 2; taken.has(out); n++) out = `${slug}-${n}`;
  taken.add(out);
  return out;
}

const MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];

/** A YYYY-MM-DD date in words, from the string alone. */
function longDate(date) {
  const y = date.slice(0, 4);
  const m = Number(date.slice(5, 7));
  const d = Number(date.slice(8, 10));
  return `${d} ${MONTHS[m - 1]} ${y}`;
}

/** The words of a body: its runs of characters other than whitespace (JS \s, as the reference's /\S+/ counts). */
function wordsOf(text) {
  let n = 0;
  let inWord = false;
  for (let i = 0; i < text.length; i++) {
    const ws = isSpace(text.charCodeAt(i));
    if (!ws && !inWord) n++;
    inWord = !ws;
  }
  return n;
}

/** Whether a UTF-16 code unit is JS \s whitespace. */
function isSpace(c) {
  return c === 32 || (c >= 9 && c <= 13) || c === 0xa0 || c === 0x1680 || (c >= 0x2000 && c <= 0x200a) ||
    c === 0x2028 || c === 0x2029 || c === 0x202f || c === 0x205f || c === 0x3000 || c === 0xfeff;
}

// ---------------------------------------------------------------- front matter

const FM_KEYS = new Set(['title', 'date', 'tags', 'draft', 'layout', 'slug', 'summary']);

/** The days of month `m` (1-12) of year `y`, by the Gregorian rule. */
function daysIn(y, m) {
  if (m === 2) return (y % 4 === 0 && y % 100 !== 0) || y % 400 === 0 ? 29 : 28;
  return m === 4 || m === 6 || m === 9 || m === 11 ? 30 : 31;
}

/** A string value: "..." with \" and \\ its only escapes, or bare, the rest of the line (never opening on " or [). */
function stringOf(raw) {
  if (raw.startsWith('"')) {
    if (raw.length < 2 || !raw.endsWith('"')) return { error: 'a quoted string is not closed' };
    let out = '';
    for (let i = 1; i < raw.length - 1; i++) {
      const c = raw[i];
      if (c === '\\') {
        const n = raw[i + 1];
        if ((n !== '"' && n !== '\\') || i + 1 === raw.length - 1) return { error: 'a quoted string holds an escape other than \\" or \\\\' };
        out += n;
        i++;
      } else if (c === '"') return { error: 'a quoted string holds a stray quote' };
      else out += c;
    }
    return { value: out };
  }
  if (raw.startsWith('[')) return { error: 'a bare string opens on [' };
  return { value: raw };
}

/** One key's value, or why it is refused. */
function valueOf(key, raw) {
  switch (key) {
    case 'title':
    case 'summary': {
      const s = stringOf(raw);
      return 'error' in s ? { error: `key "${key}": ${s.error}` } : s;
    }
    case 'date': {
      let ok = raw.length === 10 && raw[4] === '-' && raw[7] === '-';
      let y = 0, mo = 0, d = 0;
      if (ok) {
        for (const i of [0, 1, 2, 3, 5, 6, 8, 9]) {
          const c = raw.charCodeAt(i);
          if (c < 48 || c > 57) { ok = false; break; }
        }
      }
      if (ok) {
        y = Number(raw.slice(0, 4)); mo = Number(raw.slice(5, 7)); d = Number(raw.slice(8, 10));
        ok = y >= 1970 && y <= 2099 && mo >= 1 && mo <= 12 && d >= 1 && d <= daysIn(y, mo);
      }
      return ok ? { value: raw } : { error: 'key "date": not a date from 1970-01-01 to 2099-12-31 (YYYY-MM-DD)' };
    }
    case 'tags': {
      if (!raw.startsWith('[') || !raw.endsWith(']')) return { error: 'key "tags": not a list [a, b]' };
      const inner = raw.slice(1, -1);
      if (inner.trim() === '') return { value: [] };
      const tags = inner.split(',').map((t) => t.trim());
      if (tags.some((t) => t === '' || t.includes('"') || t.includes('[') || t.includes(']'))) return { error: 'key "tags": an empty tag, or one holding " [ or ]' };
      return { value: tags };
    }
    case 'draft':
      return raw === 'true' ? { value: true } : raw === 'false' ? { value: false } : { error: 'key "draft": true or false' };
    case 'layout': {
      let ok = raw.length > 0;
      for (let i = 0; i < raw.length; i++) {
        const c = raw[i];
        if (!((c >= 'a' && c <= 'z') || (c >= '0' && c <= '9') || c === '-')) { ok = false; break; }
      }
      return ok ? { value: raw } : { error: 'key "layout": not a template name' };
    }
    case 'slug': {
      let ok = raw.length >= 1 && raw.length <= 64;
      if (ok) {
        // ^[a-z0-9]+(?:-[a-z0-9]+)*$ : alnum runs joined by single dashes
        let prevDash = true; // a leading dash fails as an empty first run
        for (let i = 0; i < raw.length; i++) {
          const c = raw[i];
          if (c === '-') {
            if (prevDash) { ok = false; break; }
            prevDash = true;
          } else if ((c >= 'a' && c <= 'z') || (c >= '0' && c <= '9')) prevDash = false;
          else { ok = false; break; }
        }
        if (prevDash) ok = false; // a trailing dash leaves an empty last run
      }
      return ok ? { value: raw } : { error: 'key "slug": not a slug' };
    }
    default:
      return { error: `unknown key "${key}"` };
  }
}

/**
 * A source's front matter and body: { data, body }, or { error } with the first reason it is refused. `text` has "\n"
 * line ends. Scans lines by index so the body is one slice, never a split and rejoin of the whole text.
 */
function parseFrontMatter(text) {
  // Line 0 must be exactly "---".
  const firstNl = text.indexOf('\n');
  const line0 = firstNl === -1 ? text : text.slice(0, firstNl);
  if (line0 !== '---') return { error: 'no front matter' };
  if (firstNl === -1) return { error: 'the front matter is not closed' };
  // First pass: the front matter runs to the next line that is exactly "---"; unclosed beats any line error.
  let closeEnd = -1; // offset just past the closing line's newline (or text.length at EOF)
  let scan = firstNl + 1;
  for (;;) {
    const nl = text.indexOf('\n', scan);
    const line = nl === -1 ? text.slice(scan) : text.slice(scan, nl);
    if (line === '---') {
      closeEnd = nl === -1 ? text.length : nl + 1;
      break;
    }
    if (nl === -1) return { error: 'the front matter is not closed' };
    scan = nl + 1;
  }
  // Second pass: validate the lines between, in order.
  const data = {};
  let pos = firstNl + 1;
  let lineNo = 1; // 0-based index of the line at pos
  while (pos < closeEnd) {
    const nl = text.indexOf('\n', pos);
    const line = nl === -1 ? text.slice(pos) : text.slice(pos, nl);
    if (line === '---') break;
    let blank = true;
    for (let i = 0; i < line.length; i++) if (line[i] !== ' ' && line[i] !== '\t') { blank = false; break; }
    if (!blank && !line.startsWith('#')) {
      let k = 0;
      while (k < line.length && ((line[k] >= 'a' && line[k] <= 'z') || line[k] === '_')) k++;
      let raw = null;
      if (k > 0 && line[k] === ':') {
        if (k + 1 === line.length) raw = '';
        else if (line[k + 1] === ' ') raw = line.slice(k + 2);
      }
      if (raw === null) return { error: `line ${lineNo + 1} is not "key: value"` };
      const key = line.slice(0, k);
      raw = raw.replace(/[ \t]+$/, '');
      if (!FM_KEYS.has(key)) return { error: `unknown key "${key}"` };
      if (Object.hasOwn(data, key)) return { error: `key "${key}" is given twice` };
      if (raw === '') return { error: `key "${key}" has no value` };
      const v = valueOf(key, raw);
      if ('error' in v) return v;
      data[key] = v.value;
    }
    if (nl === -1) break;
    pos = nl + 1;
    lineNo++;
  }
  if (!Object.hasOwn(data, 'title')) return { error: 'no title' };
  return { data, body: text.slice(closeEnd) };
}

// ---------------------------------------------------------------- Markdown

/** A blank line: nothing but spaces and tabs. */
function isBlank(line) {
  for (let i = 0; i < line.length; i++) if (line[i] !== ' ' && line[i] !== '\t') return false;
  return true;
}

/** A paragraph line as it is rendered: spaces and tabs at either end dropped. */
function trimLine(line) {
  let a = 0;
  let b = line.length;
  while (a < b && (line[a] === ' ' || line[a] === '\t')) a++;
  while (b > a && (line[b - 1] === ' ' || line[b - 1] === '\t')) b--;
  return line.slice(a, b);
}

/** A fence opening line's language, or null: ``` then [A-Za-z0-9_+-]* then only spaces/tabs. */
function fenceLang(line) {
  if (!line.startsWith('```')) return null;
  let i = 3;
  while (i < line.length) {
    const c = line[i];
    if ((c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9') || c === '_' || c === '+' || c === '-') i++;
    else break;
  }
  const lang = line.slice(3, i);
  for (; i < line.length; i++) if (line[i] !== ' ' && line[i] !== '\t') return null;
  return lang;
}

/** A fence closing line: ``` then only spaces/tabs. */
function isFenceClose(line) {
  if (!line.startsWith('```')) return false;
  for (let i = 3; i < line.length; i++) if (line[i] !== ' ' && line[i] !== '\t') return false;
  return true;
}

/** A heading line's depth and text, or null (1-6 #, a space or tab, non-empty text; trailing spaces/tabs dropped). */
function headingOf(line) {
  let n = 0;
  while (n < line.length && line[n] === '#') n++;
  if (n < 1 || n > 6) return null;
  if (line[n] !== ' ' && line[n] !== '\t') return null;
  let a = n;
  while (a < line.length && (line[a] === ' ' || line[a] === '\t')) a++;
  let b = line.length;
  while (b > a && (line[b - 1] === ' ' || line[b - 1] === '\t')) b--;
  if (b === a) return null;
  return { depth: n, text: line.slice(a, b) };
}

/** A thematic break: --- or *** then only spaces/tabs. */
function isHr(line) {
  if (!line.startsWith('---') && !line.startsWith('***')) return false;
  for (let i = 3; i < line.length; i++) if (line[i] !== ' ' && line[i] !== '\t') return false;
  return true;
}

/** A bullet item's text, or null: "- " or "* " then the rest of the line. */
function bulletOf(line) {
  return (line[0] === '-' || line[0] === '*') && line[1] === ' ' ? line.slice(2) : null;
}

/** An ordered item's number and text, or null: 1-9 digits, ". ", then the rest of the line. */
function orderedOf(line) {
  let i = 0;
  while (i < line.length && line[i] >= '0' && line[i] <= '9') i++;
  if (i < 1 || i > 9 || line[i] !== '.' || line[i + 1] !== ' ') return null;
  return { num: Number(line.slice(0, i)), text: line.slice(i + 2) };
}

/** A list continuation line: at least two spaces then a non-whitespace character. */
function isContinued(line) {
  let i = 0;
  while (i < line.length && line[i] === ' ') i++;
  return i >= 2 && i < line.length && !isSpace(line.charCodeAt(i));
}

/** Whether `line` opens a fence (boolean form of fenceLang, for hot checks). */
function isFenceLine(line) {
  if (!line.startsWith('```')) return false;
  for (let i = 3; i < line.length; i++) {
    const c = line[i];
    if (!((c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9') || c === '_' || c === '+' || c === '-' || c === ' ' || c === '\t')) return false;
  }
  return true;
}

/** Whether `line` is a heading (boolean form of headingOf, for hot checks). */
function isHeadingLine(line) {
  let n = 0;
  while (n < line.length && line[n] === '#') n++;
  if (n < 1 || n > 6) return false;
  if (line[n] !== ' ' && line[n] !== '\t') return false;
  for (let i = n; i < line.length; i++) if (line[i] !== ' ' && line[i] !== '\t') return true;
  return false;
}

/** Whether `line` ends a paragraph: a blank line, a fence, a heading or a thematic break. */
function endsParagraph(line) {
  return isBlank(line) || isFenceLine(line) || isHeadingLine(line) || isHr(line);
}

/** The characters a backslash escapes. */
const ESCAPABLE = new Set(['\\', '`', '*', '_', '[', ']', '(', ')', '#', '+', '-', '.', '!', '>']);

/** The first index from `from` where s[..hi) holds `what` outside a backslash escape, or -1. */
function findUnescaped(s, what, from, hi) {
  const wlen = what.length;
  for (let j = from; j <= hi - wlen; j++) {
    if (s[j] === '\\' && j + 1 < hi && ESCAPABLE.has(s[j + 1])) {
      j++;
      continue;
    }
    if (s.startsWith(what, j)) return j;
  }
  return -1;
}

/** The first single * from `from` (one whose run is not **), outside an escape, or -1. */
function findSingleStar(s, from, hi) {
  for (let j = from; j < hi; j++) {
    const c = s[j];
    if (c === '\\' && j + 1 < hi && ESCAPABLE.has(s[j + 1])) {
      j++;
      continue;
    }
    if (c !== '*') continue;
    if (j + 1 < hi && s[j + 1] === '*') {
      j++;
      continue;
    }
    return j;
  }
  return -1;
}

/** Push the HTML-escaped form of s[lo..hi) onto `out`, in runs between the five escaped characters. */
function escapeInto(out, s, lo, hi) {
  let start = lo;
  for (let i = lo; i < hi; i++) {
    const e = ESCAPES[s[i]];
    if (e !== undefined) {
      if (i > start) out.push(s.slice(start, i));
      out.push(e);
      start = i + 1;
    }
  }
  if (hi > start) out.push(s.slice(start, hi));
}

/**
 * s[lo..hi) rendered inline, pushed onto `out`; `env.link(target)` is a link's href. Mirrors the reference's recursive
 * renderer exactly, over index ranges instead of slices, with plain runs escaped in bulk.
 */
function inlineInto(out, s, lo, hi, env) {
  let i = lo;
  let plain = lo;
  const flush = (upto) => {
    if (upto > plain) escapeInto(out, s, plain, upto);
  };
  while (i < hi) {
    const c = s[i];
    if (c !== '\\' && c !== '`' && c !== '*' && c !== '[') {
      // A plain run: advance to the next markup character in one tight scan.
      let j = i + 1;
      while (j < hi) {
        const d = s[j];
        if (d === '\\' || d === '`' || d === '*' || d === '[') break;
        j++;
      }
      i = j;
      continue;
    }
    if (c === '\\' && i + 1 < hi && ESCAPABLE.has(s[i + 1])) {
      flush(i);
      const n = s[i + 1];
      out.push(ESCAPES[n] ?? n);
      i += 2;
      plain = i;
      continue;
    }
    if (c === '`') {
      const j = s.indexOf('`', i + 1);
      if (j !== -1 && j < hi && j > i + 1) {
        flush(i);
        out.push('<code>');
        escapeInto(out, s, i + 1, j);
        out.push('</code>');
        i = j + 1;
        plain = i;
        continue;
      }
      i++;
      continue;
    }
    if (c === '*') {
      if (i + 1 < hi && s[i + 1] === '*') {
        const j = findUnescaped(s, '**', i + 2, hi);
        if (j > i + 2) {
          flush(i);
          out.push('<strong>');
          inlineInto(out, s, i + 2, j, env);
          out.push('</strong>');
          i = j + 2;
          plain = i;
          continue;
        }
        i += 2;
        continue;
      }
      const j = findSingleStar(s, i + 1, hi);
      if (j > i + 1) {
        flush(i);
        out.push('<em>');
        inlineInto(out, s, i + 1, j, env);
        out.push('</em>');
        i = j + 1;
        plain = i;
        continue;
      }
      i++;
      continue;
    }
    if (c === '[') {
      const k = findUnescaped(s, ']', i + 1, hi);
      let m = -1;
      if (k !== -1 && k + 1 < hi && s[k + 1] === '(') {
        m = s.indexOf(')', k + 2);
        if (m >= hi) m = -1;
      }
      const target = m === -1 ? '' : s.slice(k + 2, m);
      if (target !== '' && !/\s/.test(target)) {
        flush(i);
        out.push(`<a href="${escapeHtml(env.link(target))}">`);
        inlineInto(out, s, i + 1, k, env);
        out.push('</a>');
        i = m + 1;
        plain = i;
        continue;
      }
      i++;
      continue;
    }
    i++;
  }
  flush(hi);
}

/** A whole string rendered inline. */
function inline(s, env) {
  const out = [];
  inlineInto(out, s, 0, s.length, env);
  return out.join('');
}

/**
 * `src` rendered: its HTML (each block on its own lines, a "\n" after the last), its table of contents (every level 2
 * and 3 heading: level, id and its inline HTML) and its excerpt (the first paragraph's inline HTML, or "").
 */
function renderMarkdown(src, env) {
  const lines = src.split('\n');
  const ids = new Set();
  const parts = [];
  const toc = [];
  let excerpt = null;
  let i = 0;
  while (i < lines.length) {
    const line = lines[i];
    if (isBlank(line)) {
      i++;
      continue;
    }
    const lang = fenceLang(line);
    if (lang !== null) {
      const body = [];
      i++;
      while (i < lines.length && !isFenceClose(lines[i])) body.push(lines[i++]);
      i++;
      const cls = lang === '' ? '' : ` class="language-${escapeHtml(lang)}"`;
      let content = '';
      for (const l of body) content += escapeHtml(l) + '\n';
      parts.push(`<pre><code${cls}>${content}</code></pre>\n`);
      continue;
    }
    const heading = headingOf(line);
    if (heading !== null) {
      const id = uniqueSlug(slugify(heading.text), ids);
      const html = inline(heading.text, env);
      parts.push(`<h${heading.depth} id="${id}">${html}</h${heading.depth}>\n`);
      if (heading.depth === 2 || heading.depth === 3) toc.push({ level: heading.depth, id, html });
      i++;
      continue;
    }
    if (isHr(line)) {
      parts.push('<hr>\n');
      i++;
      continue;
    }
    if (line.charCodeAt(0) === 62) {
      const kept = [];
      while (i < lines.length && lines[i].charCodeAt(0) === 62) {
        const raw = lines[i];
        const t = trimLine(raw.startsWith('> ') ? raw.slice(2) : raw.slice(1));
        if (t !== '') kept.push(t);
        i++;
      }
      if (kept.length === 0) parts.push('<blockquote>\n</blockquote>\n');
      else parts.push(`<blockquote>\n<p>${inline(kept.join('\n'), env)}</p>\n</blockquote>\n`);
      continue;
    }
    const bullet = bulletOf(line);
    const ordered = bullet === null ? orderedOf(line) : null;
    if (bullet !== null || ordered !== null) {
      const isOrdered = ordered !== null;
      const items = [];
      let start = 1;
      while (i < lines.length) {
        const m = isOrdered ? orderedOf(lines[i]) : bulletOf(lines[i]);
        if (m !== null) {
          if (isOrdered && items.length === 0) start = m.num;
          items.push([trimLine(isOrdered ? m.text : m)]);
          i++;
        } else if (isContinued(lines[i])) {
          items[items.length - 1].push(trimLine(lines[i]));
          i++;
        } else break;
      }
      const tag = isOrdered ? 'ol' : 'ul';
      const open = isOrdered && start !== 1 ? `<ol start="${start}">` : `<${tag}>`;
      let block = open + '\n';
      for (const itemParts of items) block += `<li>${inline(itemParts.join('\n'), env)}</li>\n`;
      parts.push(block + `</${tag}>\n`);
      continue;
    }
    const body = [trimLine(line)];
    i++;
    while (i < lines.length && !endsParagraph(lines[i])) body.push(trimLine(lines[i++]));
    const html = inline(body.join('\n'), env);
    if (excerpt === null) excerpt = html;
    parts.push(`<p>${html}</p>\n`);
  }
  return { html: parts.join(''), toc, excerpt: excerpt ?? '' };
}

